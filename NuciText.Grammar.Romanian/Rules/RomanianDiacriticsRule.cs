    private string RegexReplaceMatchingFirstLetterCase(
        string input,
        string pattern,
        string replacement)
        => Regex.Replace(
            input,
            pattern,
            m => (char.IsUpper(m.Value[0]) ? char.ToUpper(replacement[0]) : char.ToLower(replacement[0])) + replacement[1..]
                .Replace("$1", m.Groups[1].Value)
                .Replace("$2", m.Groups[2].Value));
